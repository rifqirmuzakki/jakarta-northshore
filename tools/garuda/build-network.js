/* Builds garuda/network.js (the passenger app's timetable) from the simulated Garuda schedule.
   Input: tools/garuda/ga_raw.json (all GA flights as the simulator lists them, times in Jakarta minutes).
   Run: node tools/garuda/build-network.js */
const fs=require('fs'),vm=require('vm'),path=require('path');
const root=path.join(__dirname,'..','..');
const raw=JSON.parse(fs.readFileSync(path.join(__dirname,'ga_raw.json'),'utf8'));
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const i=html.indexOf('const TZ_CITY=');const j=html.indexOf('};',i)+1;
const TZ=vm.runInNewContext('('+html.slice(i+'const TZ_CITY='.length,j)+')');
const win={};vm.runInNewContext(fs.readFileSync(path.join(root,'schedule-changes.js'),'utf8'),{window:win});
const ai=html.indexOf('const AIR_CITY=');const AIR=vm.runInNewContext('('+html.slice(ai+'const AIR_CITY='.length,html.indexOf('};',ai)+1)+')');
const extra={Cairns:'Australia/Brisbane'},xll={};((win.JN_CHANGES_REPO||{}).changes||[]).forEach(c=>(c.airports||[]).forEach(a=>{if(a.city){extra[a.city]=a.tz;if(a.lat!=null&&a.lon!=null)xll[a.city]=[+a.lat,+a.lon]}}));
const short=a=>a.replace(/^Airbus |^Boeing /,'');
const cities={},flights=[];
raw.filter(f=>!f.multi&&f.code&&f.code.indexOf('/')<0).forEach(f=>{
  const out=f.dir==='out';
  if(!cities[f.code]){const g=xll[f.city]||(AIR[f.city]&&[AIR[f.city][0],AIR[f.city][1]]);cities[f.code]={n:f.city,tz:extra[f.city]||TZ[f.city]||'Asia/Jakarta',z:f.zone};if(g)cities[f.code].ll=g}
  const dep=out?f.t:f.t-f.blk,arr=out?f.t+f.blk:f.t;
  flights.push([f.id,out?0:1,f.code,dep,arr,f.days,f.term,short(f.ac),f.from||'',f.to||'']);
});
flights.sort((a,b)=>(+a[0].split(' ')[1])-(+b[0].split(' ')[1]));
const missing=Object.entries(cities).filter(([k,v])=>v.tz==='Asia/Jakarta'&&v.z==='I').map(([k,v])=>k);
fs.writeFileSync(path.join(root,'garuda','network.js'),'/* generated by tools/garuda/build-network.js */\nwindow.GA_NET='+JSON.stringify({hub:'JKT',cities,flights})+';\n');
