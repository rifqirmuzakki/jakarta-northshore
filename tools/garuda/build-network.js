for(const k in MORE)if(cities[k]&&!cities[k].ll)cities[k].ll=MORE[k];
const noLL=Object.entries(cities).filter(([k,v])=>!v.ll).map(([k])=>k);console.log('cities without coordinates:',noLL.join(' ')||'none');
console.log(flights.length,'flights',Object.keys(cities).length,'cities; intl cities on Jakarta tz (check):',missing.join(' '));
